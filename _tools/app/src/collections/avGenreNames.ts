/** Case, width and surrounding space do not change a tag. */
const tagKey = (name: string) => name.normalize("NFKC").trim().toLowerCase();
const KOREAN = new Map(Object.entries(AV_GENRES).map(([japanese, korean]) => [tagKey(japanese), korean]));

/** The number of tags the table names. */
export const AV_GENRE_NAME_COUNT = KOREAN.size;

/**
 * Sale, event, sample, point and quality/distribution tags are not genres of the work: they are never offered
 * from a candidate and are left out wherever stored genres are shown. Stored values are not rewritten.
 */
const HIDDEN_AV_GENRES: RegExp[] = [
  /セール/,
  /[％%]\s*オフ/,
  /感謝祭/,
  /キャンペーン/,
  /期間限定/,
  /ポイント(?:還元|\s*\d)/,
  /^サンプル動画$/,
  /^独占配信$/,
  /^DMM独占$/,
  /^配信専用$/,
  /^ハイビジョン$/,
  /^4K$/i,
  /^8K$/i,
  /^60fps$/i,
  /^ハイクオリティVR$/,
];

export function isHiddenAvGenre(genre: string): boolean {
  const name = genre.normalize("NFKC").trim();
  return HIDDEN_AV_GENRES.some(pattern => pattern.test(name)) || HIDDEN_AV_GENRES.some(pattern => pattern.test(genre.trim()));
}

/** The Korean name of one stored tag; a tag the table does not know keeps its original. */
export function avGenreName(genre: string): string {
  return KOREAN.get(tagKey(genre)) ?? genre.trim();
}

export type AvGenreView = { original: string; name: string };

/** The tags worth showing (hidden ones removed, duplicates collapsed) with their Korean names. */
export function displayAvGenres(genres: readonly string[] | null | undefined): AvGenreView[] {
  const seen = new Set<string>();
  const views: AvGenreView[] = [];
  for (const original of genres ?? []) {
    if (!original.trim() || isHiddenAvGenre(original) || seen.has(original)) continue;
    seen.add(original);
    views.push({ original, name: avGenreName(original) });
  }
  return views;
}

/** How many of these tags the display leaves out. */
export function hiddenAvGenreCount(genres: readonly string[] | null | undefined): number {
  return (genres ?? []).filter(genre => genre.trim() && isHiddenAvGenre(genre)).length;
}

/** Search matches either the Korean name or the stored original. */
export function avGenreMatches(genre: string, query: string): boolean {
  const needle = tagKey(query);
  if (!needle) return true;
  return tagKey(genre).includes(needle) || tagKey(avGenreName(genre)).includes(needle);
}
